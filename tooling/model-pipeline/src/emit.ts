import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { Document, type Material } from '@gltf-transform/core';
import { addSoup, vertexMaterial, type Soup } from './soup.ts';

/**
 * Output: every model ships gzipped (the CDN compresses scripts but not binary model types; flat-shaded meshes shrink
 * about 4×) and the game inflates it with fflate (game-kit `fetchModel`). A generated TypeScript module carries what
 * the game needs to know about the files (clip tables, material colours, attachment transforms…).
 */
export class Emitter {
  readonly dir: string;
  readonly written: { file: string; bytes: number; gzipped: number }[] = [];

  constructor(dir: string) {
    this.dir = dir;
    mkdirSync(dir, { recursive: true });
  }

  /** Write `<file>.gz`; returns its size. */
  file(file: string, bytes: Uint8Array): number {
    const gz = gzipSync(bytes, { level: 9 });
    writeFileSync(join(this.dir, `${file}.gz`), gz);
    this.written.push({ file: `${file}.gz`, bytes: bytes.length, gzipped: gz.length });
    return gz.length;
  }

  /** `export const <name> = <data> as const;` in `<file>` (a `.ts` module), with a do-not-edit header. */
  meta(file: string, name: string, data: unknown, generator: string): void {
    writeFileSync(
      join(this.dir, file),
      `// Generated by ${generator}: do not edit.\nexport const ${name} = ${compactJson(data)} as const;\n`,
    );
  }

  /** Gzipped bytes of everything written so far. */
  get total(): number {
    return this.written.reduce((n, w) => n + w.gzipped, 0);
  }
}

export const kb = (n: number) => `${(n / 1024).toFixed(0)} KB`;

/** Indented JSON with arrays of numbers (colours, transforms, bounds) kept on one line. */
export function compactJson(data: unknown): string {
  return JSON.stringify(data, null, 2).replace(
    /\[\s*(-?[\d.e+-]+(?:,\s*-?[\d.e+-]+)*)\s*\]/g,
    (_, inner: string) => `[${inner.split(/,\s*/).join(', ')}]`,
  );
}

export interface PackEntry {
  /** Node and mesh name (the game finds models by it). */
  name: string;
  soups: readonly Soup[];
  /** One of the materials `modelPack`'s `materials` made; default the shared plain vertex-colour material. */
  material?: string;
}

/**
 * A document of several models, one node + mesh each, in order (one GLB, one request, one gzip stream for many
 * props; in PlayCanvas entry i is `ContainerResource.renders[i]`). `materials` makes any extra materials (a texture
 * for the textured entries) by name.
 */
export function modelPack(
  entries: readonly PackEntry[],
  materials?: (doc: Document) => Record<string, Material>,
): Document {
  const doc = new Document();
  doc.createBuffer();
  const named = materials?.(doc) ?? {};
  const scene = doc.createScene();
  const plain = vertexMaterial(doc);
  for (const e of entries) {
    const mesh = doc.createMesh(e.name);
    const material = e.material === undefined ? plain : named[e.material];
    if (!material) throw new Error(`${e.name}: no material ${e.material}`);
    for (const s of e.soups) addSoup(doc, mesh, s, material);
    scene.addChild(doc.createNode(e.name).setMesh(mesh));
  }
  return doc;
}
