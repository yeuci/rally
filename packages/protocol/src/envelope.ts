import { z } from './zod.ts';

/** Bridge protocol version. Bump only on incompatible envelope changes. */
export const PROTOCOL_VERSION = 1 as const;

/** Milliseconds a request waits for a response before rejecting with TIMEOUT. */
export const REQUEST_TIMEOUT_MS = 10_000;

export const BridgeErrorCode = z.enum([
  'TIMEOUT',
  'NO_HOST',
  'BAD_NONCE',
  'BAD_ORIGIN',
  'INVALID_ENVELOPE',
  'INVALID_PARAMS',
  'UNKNOWN_METHOD',
  'NOT_READY',
  'ALREADY_READY',
  'NOT_SUPPORTED',
  'RATE_LIMITED',
  'MATCHMAKE_FAILED',
  'ROOM_FULL',
  'ROOM_LOCKED',
  'CONFLICT',
  'INTERNAL',
]);
export type BridgeErrorCode = z.infer<typeof BridgeErrorCode>;

export const BridgeErrorSchema = z.object({
  code: BridgeErrorCode,
  message: z.string(),
});
export type BridgeError = z.infer<typeof BridgeErrorSchema>;

export const EnvelopeKind = z.enum(['req', 'res', 'evt']);
export type EnvelopeKind = z.infer<typeof EnvelopeKind>;

/**
 * Every message crossing the WebView boundary, in either direction.
 *
 * - `req`: expects exactly one `res` with the same `id`.
 * - `res`: carries `params` (the result) or `error`, never both.
 * - `evt`: fire-and-forget.
 *
 * `nonce` is generated by the host per launch and injected before any game
 * script runs; the host drops any message whose nonce does not match.
 */
export const BridgeEnvelopeSchema = z.object({
  v: z.literal(PROTOCOL_VERSION),
  nonce: z.string().min(16),
  id: z.string().min(1).max(64),
  kind: EnvelopeKind,
  method: z.string().min(1).max(64),
  params: z.unknown().optional(),
  error: BridgeErrorSchema.optional(),
});
export type BridgeEnvelope = z.infer<typeof BridgeEnvelopeSchema>;

/** Parse an incoming JSON string into a validated envelope, or return null. */
export function parseEnvelope(json: string): BridgeEnvelope | null {
  let raw: unknown;
  try {
    raw = JSON.parse(json);
  } catch {
    return null;
  }
  const result = BridgeEnvelopeSchema.safeParse(raw);
  return result.success ? result.data : null;
}
