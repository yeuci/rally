/**
 * Self-contained upload for Colyseus Cloud (ADR 0006). `pnpm --filter @rally/game-server bundle` writes:
 *
 *   dist/cloud/build/index.js      build/index.js with every workspace package (`@rally/game-sumo-server`) inlined
 *   dist/cloud/package.json        npm dependencies only, pinned to the versions installed here (no `workspace:`)
 *   dist/cloud/ecosystem.config.cjs  copied as is (pm2, `instances: 1`)
 *
 * npm packages stay external: Colyseus Cloud runs `npm install` against that package.json, and `@colyseus/schema`
 * must stay one shared instance. The VPS does not use this: it builds in the monorepo checkout (infra/game-server).
 */
import { build } from 'esbuild';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, 'dist', 'cloud');
const readJson = async (file) => JSON.parse(await readFile(file, 'utf8'));

/** The installed package.json of `name`, found the way Node would (nearest node_modules walking up). */
function installedManifest(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const file = path.join(dir, 'node_modules', name, 'package.json');
    if (existsSync(file)) return file;
    if (path.dirname(dir) === dir) throw new Error(`[bundle] ${name} is not installed (run pnpm install)`);
  }
}

/** npm runtime deps of this package plus those of every workspace package it pulls in, recursively. */
async function collectNpmDeps(pkgDir, seen = new Set()) {
  const pkg = await readJson(path.join(pkgDir, 'package.json'));
  const deps = new Map();
  for (const [name, spec] of Object.entries(pkg.dependencies ?? {})) {
    const manifest = installedManifest(name, pkgDir);
    if (String(spec).startsWith('workspace:')) {
      if (seen.has(name)) continue;
      seen.add(name);
      for (const [n, v] of await collectNpmDeps(path.dirname(manifest), seen)) deps.set(n, v);
    } else {
      deps.set(name, (await readJson(manifest)).version);
    }
  }
  return deps;
}

const pkg = await readJson(path.join(here, 'package.json'));
const entry = path.join(here, 'build', 'index.js');
if (!existsSync(entry)) throw new Error('[bundle] build/index.js missing: run the build first (`pnpm bundle` does)');

const deps = await collectNpmDeps(here);
const external = [...deps.keys()].flatMap((name) => [name, `${name}/*`]);

await rm(out, { recursive: true, force: true });
await mkdir(path.join(out, 'build'), { recursive: true });

const result = await build({
  entryPoints: [entry],
  outfile: path.join(out, 'build', 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external,
  sourcemap: 'linked',
  metafile: true,
  logLevel: 'warning',
});

// Anything external that is neither a Node builtin nor a pinned dependency would be missing on Colyseus Cloud.
const allowed = new Set(deps.keys());
const bareName = (spec) => (spec.startsWith('@') ? spec.split('/').slice(0, 2) : spec.split('/').slice(0, 1)).join('/');
const stray = new Set();
for (const output of Object.values(result.metafile.outputs)) {
  for (const imp of output.imports) {
    if (!imp.external || imp.path.startsWith('node:')) continue;
    if (!allowed.has(bareName(imp.path))) stray.add(imp.path);
  }
}
if (stray.size) throw new Error(`[bundle] undeclared external imports: ${[...stray].join(', ')}`);

await writeFile(
  path.join(out, 'package.json'),
  JSON.stringify(
    {
      name: 'rally-game-server',
      version: pkg.version,
      private: true,
      description: 'Generated by apps/game-server/bundle.config.mjs. Do not edit; rebuild instead.',
      type: 'module',
      main: 'build/index.js',
      engines: pkg.engines,
      scripts: { start: 'node build/index.js', build: 'echo prebuilt by bundle.config.mjs' },
      dependencies: Object.fromEntries([...deps].sort(([a], [b]) => a.localeCompare(b))),
    },
    null,
    2,
  ) + '\n',
);
await copyFile(path.join(here, 'ecosystem.config.cjs'), path.join(out, 'ecosystem.config.cjs'));

const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.info(`[bundle] dist/cloud ready (${(bytes / 1024).toFixed(0)} KiB; deps: ${[...deps.keys()].join(', ')})`);
